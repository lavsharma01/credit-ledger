// Copies the contract ABI and deployment addresses from ../shared (owned by the
// contracts team) into src/contracts as typed TS modules. Runs automatically
// before `npm run dev`, `npm run build` and after `npm install`.
// Next.js (Turbopack) cannot import files outside the web/ project root, so we
// copy instead of importing ../shared directly. The output is gitignored.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sharedDir = resolve(here, "../../shared");
const outDir = resolve(here, "../src/contracts");

function readJson(name) {
  const path = resolve(sharedDir, name);
  if (!existsSync(path)) {
    console.error(`[sync-contracts] Missing ${path}. Pull main to get /shared.`);
    process.exit(1);
  }
  return JSON.parse(readFileSync(path, "utf8"));
}

// Only rewrite when content changed so a running dev server doesn't reload needlessly.
function writeIfChanged(name, content) {
  const path = resolve(outDir, name);
  if (existsSync(path) && readFileSync(path, "utf8") === content) return;
  writeFileSync(path, content);
  console.log(`[sync-contracts] wrote src/contracts/${name}`);
}

const header = "// AUTO-GENERATED by scripts/sync-contracts.mjs from /shared. Do not edit.\n";
const abi = readJson("CreditLedger.abi.json");
const deployments = readJson("deployments.json");
if (!Array.isArray(abi)) {
  console.error("[sync-contracts] CreditLedger.abi.json is not an ABI array.");
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
writeIfChanged("abi.ts", `${header}export const creditLedgerAbi = ${JSON.stringify(abi, null, 2)} as const;\n`);
writeIfChanged(
  "deployments.ts",
  `${header}export const deployments: Record<string, { chainId: number; address: string; explorerUrl?: string }> = ${JSON.stringify(deployments, null, 2)};\n`,
);
